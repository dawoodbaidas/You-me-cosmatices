import assert from 'node:assert/strict'
export async function checkInteractions(page) {
  await page.setViewport({width:390,height:844,isMobile:true,hasTouch:true})
  await page.goto('http://127.0.0.1:5073/category/all',{waitUntil:'networkidle0'})
  const card='[data-testid^="product-"]'
  const first=await page.$eval(card,e=>`[data-testid="${e.dataset.testid}"]`)
  const select=part=>`${first} [class*="_${part}_"]`
  const click=async selector=>{await page.$eval(selector,e=>e.click());await new Promise(r=>setTimeout(r,100))}
  const qty=()=>page.$eval(select('counter')+' output',e=>Number(e.textContent))
  await click(select('add'));assert.equal(await qty(),1)
  await click(select('tag'));assert.equal(await qty(),2)
  await click(select('counter')+' button:last-child');assert.equal(await qty(),3)
  await click(select('counter')+' button:first-child');assert.equal(await qty(),2)
  await click(select('counter')+' button:first-child');await click(select('counter')+' button:first-child')
  assert.ok(await page.$(select('add')))
  const image=await page.$(select('imageButton'))
  await image.evaluate(e=>e.scrollIntoView({block:'center',behavior:'instant'}))
  await new Promise(r=>setTimeout(r,300))
  const box=await image.boundingBox(),x=box.x+box.width/2,y=box.y+box.height/2
  const cdp=await page.createCDPSession()
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]})
  await new Promise(r=>setTimeout(r,450))
  assert.equal(await page.$eval(first+' [data-lens]',e=>e.hidden),false)
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  assert.equal(await page.$eval(first+' [data-lens]',e=>e.hidden),true)
  assert.equal(await page.$('.quickview-dialog[open]'),null)
  await new Promise(r=>setTimeout(r,500))
  await page.focus(select('zoom'));await page.keyboard.press('Enter')
  assert.equal(await page.$eval(first+' [data-lens]',e=>e.hidden),false)
  await page.keyboard.press('ArrowRight');await page.keyboard.press('Escape')
  assert.equal(await page.$eval(first+' [data-lens]',e=>e.hidden),true)
  await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}])
  assert.equal(await page.$eval(first,e=>getComputedStyle(e).animationName),'none')
  const images=await page.$$eval(card+' img',els=>els.map(e=>({fit:getComputedStyle(e).objectFit,loading:e.loading,srcset:e.srcset})))
  assert.ok(images.every(e=>e.fit==='cover'&&!/\s(?:1080|1200|1920|2048|3840)w/.test(e.srcset)))
  assert.deepEqual(images.slice(0,2).map(e=>e.loading),['eager','eager'])
  assert.ok(images.slice(2).every(e=>e.loading==='lazy'))
  await cdp.detach()
  console.log('Passed: add/tag/increment/decrement/removal; touch lens and click suppression; keyboard lens; reduced motion; capped responsive images')
}
