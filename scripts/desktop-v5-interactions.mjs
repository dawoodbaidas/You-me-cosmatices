import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
import { writeFile } from 'node:fs/promises'
const { default: puppeteer } = await import(pathToFileURL('C:/Users/ONE BY ONE/AppData/Local/npm-cache/_npx/0f94ee7615faf582/node_modules/puppeteer-core/lib/puppeteer/puppeteer-core.js').href)
const browser = await puppeteer.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'})
const checks=[]
try {
 const page=await browser.newPage()
 await page.setViewport({width:1440,height:1000})
 await page.goto('http://localhost:3010',{waitUntil:'networkidle0'})
 await new Promise(r=>setTimeout(r,2500))
 await page.evaluate(()=>window.scrollTo({top:300,behavior:'instant'}))
 await new Promise(r=>setTimeout(r,1000))
 await page.screenshot({path:'artifacts/desktop-v5/hero-scroll-mid.png'})
 await page.$eval('.campaign-photo-1',el=>el.click())
 await page.waitForSelector('.quickview-dialog[open]')
 await page.keyboard.press('Escape')
 checks.push('desktop hero photograph opens product details; Escape closes')
 await page.$eval('.campaign-note button',el=>el.click())
 await new Promise(r=>setTimeout(r,1200))
 await page.$eval('.object-cart-v2',el=>el.click())
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('you-and-me-cart-v1')||'[]').length===1)
 await page.$eval('.header-bag',el=>el.click())
 await page.waitForSelector('.cart-dialog[open]')
 assert.ok((await page.$eval('.cart-sheet',el=>el.innerText)).includes('1'))
 await page.screenshot({path:'artifacts/desktop-v5/cart-desktop.png'})
 await page.keyboard.press('Escape')
 await page.reload({waitUntil:'networkidle0'})
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('you-and-me-cart-v1'))[0].quantity),1)
 checks.push('CTA navigates to catalogue; add to cart; drawer opens; cart persists across reload')
 await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}])
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}))
 assert.equal(await page.$eval('.campaign-note',el=>getComputedStyle(el).opacity),'1')
 checks.push('reduced motion leaves desktop scene visible')
 await page.setViewport({width:390,height:1000})
 assert.equal(await page.$eval('.desktop-campaign',el=>getComputedStyle(el).display),'none')
 checks.push('resizing back to mobile hides desktop scene and cleans up desktop media context')
 await writeFile('artifacts/desktop-v5/interactions.json',JSON.stringify(checks,null,2))
 console.log(checks)
} finally {await browser.close()}
